export function useI18n() {
  const currentLang = useState<Language>('lang', () => 'uz')

  if (import.meta.client) {
    const saved = localStorage.getItem('lang') as Language
    if (saved && (saved === 'uz' || saved === 'ru' || saved === 'en') && currentLang.value !== saved) {
      currentLang.value = saved
      document.documentElement.lang = saved
    }
  }

  const setLang = (lang: Language) => {
    currentLang.value = lang
    if (import.meta.client) {
      localStorage.setItem('lang', lang)
      document.documentElement.lang = lang
    }
  }

  const t = (key: string, params: Record<string, any> = {}): string => {
    let text = translations[currentLang.value]?.[key] || translations.uz[key] || key
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
    return text
  }

  const tDistrict = (name: string): string => {
    if (!name) return ''
    if (currentLang.value === 'ru' && DISTRICT_NAMES_RU[name]) {
      return DISTRICT_NAMES_RU[name]
    }
    return name
  }

  const formatPrice = (val: number, isSale: boolean = false): string => {
    const formatted = (val || 0).toLocaleString('ru-RU').replace(/\u00a0/g, ' ')
    const unit = currentLang.value === 'ru' ? 'сум' : currentLang.value === 'en' ? 'UZS' : 'so‘m'
    return `${formatted} ${unit}`
  }

  return {
    currentLang,
    setLang,
    t,
    tDistrict,
    formatPrice,
  }
}
